<?php

namespace App\Http\Controllers;

use App\Models\Scan;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Mpdf\Mpdf;

class ReportController extends Controller
{
    public function download($id)
    {
        $scan = Scan::findOrFail($id);

        // Security check: Owner or Public scan
        if ($scan->user_id !== null && (!Auth::check() || Auth::id() !== $scan->user_id)) {
            abort(403, 'Unauthorized access to this intelligence briefing.');
        }

        $results = $scan->results;
        
        // Pass the language preference if available, default to English
        $lang = request()->get('lang', 'en');

        // Synthesis text (Raw, mPDF handles shaping)
        $aiSummaryAr = $results['aiSummary']['ar'] ?? 'لا يوجد تحليل متاح.';
        $aiSummaryEn = $results['aiSummary']['en'] ?? 'No synthesis available.';

        // Translation Map (Raw, mPDF handles shaping)
        $t = [
            'briefing' => 'Security Briefing',
            'case_id' => 'Case ID',
            'classification' => 'Classification',
            'target_url' => 'Target URL',
            'date' => 'Date',
            'trust_score' => 'Trust Score',
            'safe' => 'SAFE / NO THREAT DETECTED',
            'suspicious' => 'SUSPICIOUS / PROCEED WITH CAUTION',
            'malicious' => 'MALICIOUS / IMMEDIATE QUARANTINE',
            'verified' => 'Verified through neural behavioral analysis and multiple external threat databases.',
            'synthesis' => 'AI Security Synthesis',
            'infra' => 'Technical Infrastructure',
            'parameter' => 'Parameter',
            'value' => 'Value / Result',
            'ip' => 'IP Address',
            'asn' => 'ASN / Network',
            'location' => 'Server Location',
            'gsb' => 'Google Safe Browsing',
            'indicators' => 'Threat Indicators (IOCs)',
            'all_engines' => 'Full Engine Intelligence List',
            'no_indicators' => 'No explicit threat indicators found in standard intelligence databases.',
            'external' => 'External Intelligence Summary',
            'engine' => 'Engine Type',
            'ratio' => 'Detection Ratio',
            'primary' => 'Primary Classification',
            'end' => 'END OF BRIEFING - GENERATED BY LINKESHIELD AI ENGINE V2.0',
            'threat' => 'THREAT DETECTED',
            'clear' => 'CLEAR',
            'unit' => 'LinkeShield AI Intelligence Unit'
        ];

        if ($lang === 'ar') {
            $t = [
                'briefing' => 'تقرير أمني',
                'case_id' => 'رقم القضية',
                'classification' => 'التصنيف',
                'target_url' => 'الرابط المستهدف',
                'date' => 'التاريخ',
                'trust_score' => 'مؤشر الثقة',
                'safe' => 'آمن / لم يتم اكتشاف تهديد',
                'suspicious' => 'مشبوه / يرجى توخي الحذر',
                'malicious' => 'ضار / حجر صحي فوري',
                'verified' => 'تم التحقق من خلال التحليل السلوكي العصبي وقواعد بيانات التهديدات الخارجية المتعددة.',
                'synthesis' => 'ملخص الذكاء الاصطناعي الأمني',
                'infra' => 'البنية التحتية التقنية',
                'parameter' => 'المعلمة',
                'value' => 'القيمة / النتيجة',
                'ip' => 'عنوان IP',
                'asn' => 'الشبكة / ASN',
                'location' => 'موقع الخادم',
                'gsb' => 'جوجل للتصفح الآمن',
                'indicators' => 'مؤشرات التهديد (IOCs)',
                'all_engines' => 'قائمة استخبارات المحركات الكاملة',
                'no_indicators' => 'لم يتم العثور على مؤشرات تهديد صريحة في قواعد بيانات الاستخبارات القياسية.',
                'external' => 'ملخص الاستخبارات الخارجية',
                'engine' => 'نوع المحرك',
                'ratio' => 'نسبة الاكتشاف',
                'primary' => 'التصنيف الأساسي',
                'end' => 'نهاية التقرير - تم إنشاؤه بواسطة محرك LINKESHIELD AI V2.0',
                'threat' => 'تم اكتشاف تهديد',
                'clear' => 'سليم',
                'unit' => 'وحدة استخبارات LinkeShield AI'
            ];
        }

        $data = [
            'scan' => $scan,
            'results' => $results,
            'lang' => $lang,
            't' => $t,
            'aiSummaryAr' => $aiSummaryAr,
            'aiSummaryEn' => $aiSummaryEn,
            'date' => $scan->created_at->format('Y-m-d H:i:s'),
            'case_id' => strtoupper(substr(md5($scan->id), 0, 8)) . '-' . $scan->id,
            'stamp' => $lang === 'ar' ? 'سري للغاية' : 'Top Secret',
        ];

        // Configure mPDF
        $mpdf = new Mpdf([
            'mode' => 'utf-8',
            'format' => 'A4',
            'default_font_size' => 12,
            'margin_left' => 15,
            'margin_right' => 15,
            'margin_top' => 15,
            'margin_bottom' => 15,
            'fontDir' => array_merge((new \Mpdf\Config\ConfigVariables())->getDefaults()['fontDir'], [
                storage_path('fonts'),
            ]),
            'fontdata' => (new \Mpdf\Config\FontVariables())->getDefaults()['fontdata'] + [
                'zain' => [
                    'R' => 'Zain-Regular.ttf',
                    'B' => 'Zain-Bold.ttf',
                    'useOTL' => 0xFF,
                    'useKashida' => 75,
                ]
            ],
            'autoScriptToLang' => true,
            'autoLangToFont' => true,
        ]);

        $html = view('reports.briefing', $data)->render();
        
        $mpdf->SetWatermarkText('LinkeShield AI');
        $mpdf->showWatermarkText = true;
        $mpdf->watermark_font = 'zain';
        $mpdf->watermarkTextAlpha = 0.05;

        $mpdf->WriteHTML($html);
        
        $filename = 'Briefing_' . $data['case_id'] . '.pdf';

        return $mpdf->Output($filename, 'D');
    }
}
